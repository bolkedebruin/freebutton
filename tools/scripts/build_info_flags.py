#!/usr/bin/env python3
"""
PlatformIO pre-script: build metadata for the firmware.

Runs before the build (referenced from platformio.ini extra_scripts).

  FIRMWARE_VERSION  - version from the repo-root VERSION file, a define on
                      every compile command. It changes only with a release.

  fb_build_info.h   - a generated header in $BUILD_DIR/generated (on the
                      include path) with what changes between builds:
                        GIT_COMMIT   short commit hash (or "unknown")
                        BUILD_DIRTY  1 if the working tree is dirty, else 0

The commit and the dirty flag are NOT defines on the command line: a define
there is part of every object's build signature, so a new commit (or the first
edit after one) would recompile the whole firmware. The header is rewritten
only when its content changes, and only the files that include it are built
again. For the same reason there is no build time in it: it would differ on
every build.

Never fails the build: if git or the VERSION file is unavailable, it falls back
to "unknown"/0.
"""

import sys
from pathlib import Path

Import("env")  # noqa: F821 - provided by PlatformIO SCons at runtime

# SCons exec context has no __file__; derive paths from the project directory.
REPO_ROOT = Path(env.subst("$PROJECT_DIR")).resolve()  # noqa: F821
SCRIPTS_DIR = REPO_ROOT / "tools" / "scripts"
VERSION_FILE = REPO_ROOT / "VERSION"
GENERATED_DIR = Path(env.subst("$BUILD_DIR")) / "generated"  # noqa: F821
HEADER = GENERATED_DIR / "fb_build_info.h"

# Reuse the git logic from build_info.py (same directory).
sys.path.insert(0, str(SCRIPTS_DIR))
try:
    from build_info import get_git_info
except Exception:  # defensive fallback
    def get_git_info():
        return {"commit": "unknown", "branch": "unknown", "dirty": False}


def read_version():
    try:
        version = VERSION_FILE.read_text().strip()
        return version or "unknown"
    except Exception:
        return "unknown"


def write_if_changed(path, text):
    """True when the file was written; an unchanged file keeps its date."""
    try:
        if path.read_text() == text:
            return False
    except OSError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return True


git_info = get_git_info()
version = read_version()

commit = git_info.get("commit") or "unknown"
dirty = 1 if git_info.get("dirty") else 0

header = (
    "// Generated by tools/scripts/build_info_flags.py. Do not edit.\n"
    "#pragma once\n"
    f'#define GIT_COMMIT "{commit}"\n'
    f"#define BUILD_DIRTY {dirty}\n"
)
written = write_if_changed(HEADER, header)

env.Append(  # noqa: F821
    CPPDEFINES=[("FIRMWARE_VERSION", env.StringifyMacro(version))],  # noqa: F821
    CPPPATH=[str(GENERATED_DIR)],
)

print(f"[build_info] version={version} commit={commit} dirty={dirty} "
      f"({HEADER.name} {'written' if written else 'unchanged'})")
