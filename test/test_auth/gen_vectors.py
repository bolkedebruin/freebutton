#!/usr/bin/env python3
"""Generate test/test_auth/sigv4_vectors.h from the AWS SigV4 test suite.

The suite ships with aws-c-auth (tests/aws-signing-test-suite/v4); fetch it with

    git clone --depth 1 --filter=blob:none --sparse https://github.com/awslabs/aws-c-auth.git
    git -C aws-c-auth sparse-checkout set tests/aws-signing-test-suite

and run

    python3 test/test_auth/gen_vectors.py aws-c-auth/tests/aws-signing-test-suite/v4 > test/test_auth/sigv4_vectors.h

Only vectors whose canonical URI follows the S3 rules (encode once, no
"."/".." or "//" normalisation) are emitted: the device verifies S3-style.
The others are listed in a comment.
"""
import json
import os
import sys

UNRESERVED = set(b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_.~")


def s3_encode(raw: bytes, keep_slash: bool) -> str:
    out = []
    for b in raw:
        if b in UNRESERVED or (keep_slash and b == 0x2F):
            out.append(chr(b))
        else:
            out.append("%%%02X" % b)
    return "".join(out)


def server_decode(s: bytes) -> bytes:
    """ESPAsyncWebServer urlDecode: %XX and '+' -> ' '."""
    out = bytearray()
    i = 0
    while i < len(s):
        c = s[i]
        if c == 0x25 and i + 2 < len(s):
            out.append(int(s[i + 1:i + 3], 16))
            i += 3
        elif c == 0x2B:
            out.append(0x20)
            i += 1
        else:
            out.append(c)
            i += 1
    return bytes(out)


def parse_request(path):
    data = open(path, "rb").read()
    head, _, body = data.partition(b"\n\n")
    lines = head.split(b"\n")
    method, rest = lines[0].split(b" ", 1)
    target = rest.rsplit(b" ", 1)[0]
    headers = []
    for line in lines[1:]:
        if not line:
            continue
        if line[:1] in (b" ", b"\t") and headers:
            headers[-1][1] += b"\n" + line
            continue
        name, _, value = line.partition(b":")
        headers.append([name, value])
    return method, target, headers, body


def c_str(b: bytes) -> str:
    out = ['"']
    for ch in b:
        if ch == 0x22:
            out.append('\\"')
        elif ch == 0x5C:
            out.append("\\\\")
        elif ch == 0x0A:
            out.append("\\n")
        elif 0x20 <= ch < 0x7F and ch != 0x3F:  # '?' escaped to dodge trigraphs
            out.append(chr(ch))
        else:
            out.append("\\%03o" % ch)
    out.append('"')
    return "".join(out)


def headers_array(name, headers):
    items = ", ".join("%s, %s" % (c_str(n), c_str(v)) for n, v in headers)
    return "static const char* const %s[] = {%s%snullptr};" % (name, items, ", " if items else "")


def main(root):
    out = []
    skipped = []
    entries = []
    for name in sorted(os.listdir(root)):
        d = os.path.join(root, name)
        if not os.path.isfile(os.path.join(d, "header-signature.txt")):
            continue
        ctx = json.load(open(os.path.join(d, "context.json")))
        method, target, _, body = parse_request(os.path.join(d, "request.txt"))
        creq_h = open(os.path.join(d, "header-canonical-request.txt"), "rb").read()
        raw_path = target.split(b"?", 1)[0]
        s3_uri = s3_encode(server_decode(raw_path), True).encode()
        if creq_h.split(b"\n")[1] != s3_uri:
            skipped.append("%s (canonical URI %s, S3-style %s)"
                           % (name, creq_h.split(b"\n")[1].decode(), s3_uri.decode()))
            continue
        _, h_target, h_headers, _ = parse_request(os.path.join(d, "header-signed-request.txt"))
        _, q_target, q_headers, _ = parse_request(os.path.join(d, "query-signed-request.txt"))
        creq_q = open(os.path.join(d, "query-canonical-request.txt"), "rb").read()
        sig_h = open(os.path.join(d, "header-signature.txt")).read().strip()
        sig_q = open(os.path.join(d, "query-signature.txt")).read().strip()
        ident = name.replace("-", "_")
        out.append(headers_array("h_" + ident, h_headers))
        out.append(headers_array("q_" + ident, q_headers))
        entries.append("    {%s, %s, %s, h_%s, %s, %s, %s, q_%s, %s, %s, %s, %s, %s, %s, %s}," % (
            c_str(name.encode()), c_str(method), c_str(h_target), ident, c_str(body), c_str(creq_h),
            c_str(sig_h.encode()), ident, c_str(q_target), c_str(creq_q), c_str(sig_q.encode()),
            c_str(creq_q.split(b"\n")[-1]), c_str(ctx["service"].encode()),
            c_str(ctx["credentials"]["access_key_id"].encode()),
            c_str(ctx["credentials"]["secret_access_key"].encode())))
    print("// Generated by test/test_auth/gen_vectors.py from the AWS SigV4 test suite")
    print("// (aws-c-auth tests/aws-signing-test-suite/v4). Do not edit.")
    print("// Skipped (generic SigV4 path normalisation, not S3 rules):")
    for s in skipped:
        print("//   " + s)
    print("#pragma once")
    print("struct SuiteVector {")
    print("    const char* name; const char* method;")
    print("    const char* headerTarget; const char* const* headerHeaders; const char* body;")
    print("    const char* headerCanonical; const char* headerSignature;")
    print("    const char* const* queryHeaders; const char* queryTarget; const char* queryCanonical;")
    print("    const char* querySignature; const char* queryPayload;")
    print("    const char* service; const char* accessKeyId; const char* secret;")
    print("};")
    print("\n".join(out))
    print("static const SuiteVector kSuite[] = {")
    print("\n".join(entries))
    print("};")


if __name__ == "__main__":
    main(sys.argv[1])
